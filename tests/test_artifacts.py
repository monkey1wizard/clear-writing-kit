def read_lf(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def split_sources_section(name: str) -> tuple[str, str]:
    """Return the rule text above the closing citation section and the section itself."""
    text = read_lf(ROOT / CORE / "references" / (name + ".md"))
    heading = "\n## " + SOURCES_SECTIONS[name][0] + "\n"
    if text.count(heading) != 1:
        raise AssertionError(f"{name}.md must contain exactly one citation section heading")
    prefix, section = text.split(heading)
    if "\n## " in section:
        raise AssertionError(f"{name}.md citation section must be the last section")
    return prefix, heading.lstrip("\n") + section


def reference_entries() -> dict[str, tuple[str, str]]:
    """Map each citation key in docs/references.md to its group heading and entry text."""
    entries, group = {}, None
    for line in read_lf(ROOT / "docs/references.md").splitlines():
        if line.startswith("## "):
            group = line[3:]
            continue
        match = re.match(r"^- `\[([A-Za-z][A-Za-z0-9]*)\]` (.+)$", line)
        if match:
            if match.group(1) in entries:
                raise AssertionError("Duplicate citation key: " + match.group(1))
            entries[match.group(1)] = (group, match.group(2))
    return entries


class Artifacts(unittest.TestCase):
    def test_reference_citation_contract(self):
        reference_text = read_lf(ROOT / "docs/references.md")
        groups = re.findall(r"^## (.+)$", reference_text, re.M)
        self.assertEqual(groups, ["Standards and guidelines", "Software"])
        self.assertNotRegex(reference_text, r"(?i)used by")
        self.assertNotRegex(reference_text, CERTIFICATION_CLAIM)
        entries = reference_entries()
        self.assertTrue(entries)

        package = json.loads((ROOT / "writing/package.json").read_text(encoding="utf-8"))
        pinned = {**package.get("dependencies", {}), **package.get("devDependencies", {})}
        for group in groups:
            order = []
            for key, (entry_group, entry) in entries.items():
                if entry_group != group:
                    continue
                match = re.match(r"^(.+?)\. \((\d{4}|n\.d\.)\)\. \*\[[^\]]+\]\(https://[^)]+\)\*", entry)
                self.assertIsNotNone(match, key)
                order.append((match.group(1).casefold(), match.group(2)))
                if group == "Software":
                    npm = re.search(r"https://www\.npmjs\.com/package/([^/)]+)/v/([^)]+)\)", entry)
                    if npm:
                        name, version = npm.groups()
                        self.assertEqual(pinned.get(name), version, key)
                        self.assertIn(f"(Version {version})", entry)
                        self.assertTrue(key.endswith(version.replace(".", "")), key)
                    else:
                        # Host-provided software has no repository pin. Cite it without a version claim.
                        self.assertNotIn("Version", entry, key)
                        self.assertRegex(entry, r"Retrieved [A-Z][a-z]+ \d{1,2}, \d{4}, from <https://", key)
            self.assertEqual(order, sorted(order), group)
        for key in ("ISO2023", "ASDSTE1002025", "SpeakHumanTW2026", "Bunka2022"):
            self.assertEqual(entries[key][0], "Standards and guidelines", key)
        for key in ("Textlint1580", "TextlintRulePresetJaTechnicalWriting1202", "TextlintRuleWriteGood200", "TextlintRuleNoZeroWidthSpaces101", "ZhtwMCP"):
            self.assertEqual(entries[key][0], "Software", key)
        self.assertIn("e180f0a", entries["SpeakHumanTW2026"][1])

        self.assertNotRegex(persistent_core(ROOT), BARE_CITATION_KEY)
        maintained = {p.stem for p in (ROOT / CORE / "references").glob("*.md")}
        self.assertEqual(maintained, set(SOURCES_SECTIONS))
        cited = set()
        for name in sorted(maintained):
            with self.subTest(rule_file=name):
                prefix, section = split_sources_section(name)
                self.assertEqual(hashlib.sha256(prefix.rstrip("\n").encode("utf-8")).hexdigest(), RULE_PREFIX_SHA256[name])
                self.assertNotRegex(prefix, CITATION_KEY)
                self.assertIn("](" + REFERENCES_URL + ")", section)
                self.assertNotRegex(prefix + section, RELATIVE_DOCS_LINK)
                self.assertNotRegex(section, CERTIFICATION_CLAIM)
                self.assertIn(SOURCES_SECTIONS[name][1], section)
                keys = set(CITATION_KEY.findall(section))
                self.assertLessEqual(REQUIRED_CITATIONS[name], keys)
                cited |= keys
                for line in section.splitlines():
                    if "`[SpeakHumanTW2026]`" in line:
                        self.assertIn("e180f0a", line)
                        self.assertTrue("informed by" in line or "受其啟發" in line, line)
                        self.assertNotRegex(line, r"(?i)deriv|follow|推導|依據")
        self.assertEqual(cited - set(entries), set(), "cited keys missing from docs/references.md")
        self.assertEqual(set(entries) - cited, set(), "reference entries without a rule-file citation")

