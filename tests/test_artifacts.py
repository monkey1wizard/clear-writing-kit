    def test_agents_block_has_required_content_and_byte_limit(self):
        block = render_agents_block()
        skill = (ROOT / CORE / "SKILL.md").read_text(encoding="utf-8")
        version = re.search(r"^  version:\s*([^\s]+)\s*$", skill, re.M).group(1)
